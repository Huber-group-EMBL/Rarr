#' @importFrom grumpy convert_bytes_to_array
codec_bytes_decode <- function(
  input,
  outer_chunk_dim,
  datatype,
  endian,
  ...
) {
  if (length(datatype$base_type) == 1L && datatype$base_type == "bfloat") {
    return(.Call(
      "type_convert_bfloat",
      input,
      datatype$nbytes,
      outer_chunk_dim,
      endian,
      PACKAGE = "Rarr"
    ))
  }
  convert_bytes_to_array(
    input,
    datatype$base_type,
    outer_chunk_dim,
    datatype$nbytes,
    endian
  )
}

codec_bytes_encode <- function(input, datatype, endian) {
  if (is.character(input)) {
    ## we need to create fixed length strings either via padding or trimming
    if (datatype$base_type == "unicode") {
      to <- if (endian == "little") "UCS-4LE" else "UCS-4BE"
      raw_list <- iconv(input, to = to, toRaw = TRUE)
    } else {
      raw_list <- iconv(input, toRaw = TRUE)
    }
    unlist(
      lapply(
        raw_list,
        FUN = function(x, nbytes) {
          # NULL generated by iconv() for NA_character_
          if (is.null(x)) {
            x <- writeBin(NA_integer_, raw())
          }
          length(x) <- nbytes
          return(x)
        },
        nbytes = datatype$nbytes
      )
    )
  } else {
    if (is.na(endian)) {
      endian <- "little"
    }
    writeBin(input, raw(), size = datatype$nbytes, endian = endian)
  }
}


# -- Variable-length UTF-8 ------------------------
`codec_vlen-utf8_encode` <- function(input, ...) {
  # NA_character_ is written as the string "NA"
  .Call("codec_vlen_utf8_encode_c", input, PACKAGE = "Rarr")
}

`codec_vlen-utf8_decode` <- function(
  input,
  outer_chunk_dim,
  index_in_chunk = NULL,
  ...
) {
  # Strings after the last required element (in column-major order) are
  # discarded later in the reading pipeline, so there is no need to decode
  # them.
  n_needed <- NULL
  if (
    !is.null(index_in_chunk) &&
      !identical(index_in_chunk, lapply(outer_chunk_dim, seq_len))
  ) {
    last <- vapply(index_in_chunk, max, integer(1L))
    strides <- cumprod(c(1L, outer_chunk_dim[-length(outer_chunk_dim)]))
    n_needed <- sum((last - 1L) * strides) + 1L
  }
  .Call(
    "codec_vlen_utf8_decode_c",
    input,
    outer_chunk_dim,
    n_needed,
    PACKAGE = "Rarr"
  )
}

codec_sharding_indexed_decode <- function(
  input,
  outer_chunk_dim,
  index_in_chunk,
  datatype,
  fill_value,
  ...
) {
  config <- list(...)
  chunk_dim <- unlist(config$chunk_shape)
  nb_dims <- length(outer_chunk_dim)
  index_shape <- c(2L, outer_chunk_dim / chunk_dim)
  index_length <- prod(index_shape)
  index_nbytes <- index_length * 8L
  names(config$index_codecs) <- vapply(
    config$index_codecs,
    function(x) x$name,
    character(1L)
  )
  if ("crc32c" %in% names(config$index_codecs)) {
    index_nbytes <- index_nbytes + 4L
  }

  index_location <- config$index_location %||% "end"
  if (index_location == "end") {
    index_raw <- input[seq.int(to = length(input), length.out = index_nbytes)]
  } else {
    index_raw <- input[seq_len(index_nbytes)]
  }

  index <- readBin(
    index_raw,
    what = "integer",
    n = index_length,
    size = 8L,
    endian = config$index_codecs$bytes$configuration[["endian"]] %||%
      .Platform$endian
  )
  dim(index) <- index_shape
  index <- codec_transpose_decode(index, c(1L, rev(seq_len(nb_dims) + 1L)))

  inner_codecs <- config$codecs |>
    setNames(vapply(
      config$codecs,
      function(x) x$name,
      FUN.VALUE = character(1L)
    ))
  # Inner chunks are C-ordered like any other chunk, so inject the same default
  # transpose codec that is added for unsharded arrays.
  if (is.null(inner_codecs[["transpose"]])) {
    inner_codecs <- c(
      list(
        transpose = list(
          name = "transpose",
          configuration = list(order = seq_along(chunk_dim) - 1L)
        )
      ),
      inner_codecs
    )
  }
  configured_decoders <- .configure_codecs(inner_codecs, operation = "decode")

  # Inner chunks that don't overlap `index_in_chunk` are discarded by the
  # caller, so skip reading and decoding them. They stay as `fill_value`.
  needed <- TRUE
  if (
    !is.null(index_in_chunk) &&
      !identical(index_in_chunk, lapply(outer_chunk_dim, seq_len))
  ) {
    needed <- lapply(seq_len(nb_dims), function(d) {
      flag <- logical(index_shape[[d + 1L]])
      flag[(index_in_chunk[[d]] - 1L) %/% chunk_dim[[d]] + 1L] <- TRUE
      flag
    })
    needed <- as.vector(Reduce(function(a, b) outer(a, b, `&`), needed))
  }

  # FIXME: Once stores are implemented, treat this as a memory store and use
  # `read_data()` directly
  shard <- array(fill_value, dim = outer_chunk_dim)

  index_in_chunk <- lapply(chunk_dim, seq_len)
  n_chunks <- dim(index)[-1L]
  index <- matrix(index, nrow = 2L)
  non_empty <- index[2L, ] > 0L
  to_read <- which(non_empty & needed)
  for (i in to_read) {
    # Offset caused by index being at the start is already contained in the
    # offset returned by index.
    chunk_raw <- input[seq.int(index[1L, i] + 1L, length.out = index[2L, i])]
    chunk <- read_chunk(
      chunk_raw,
      chunk_dim = chunk_dim,
      decoders = configured_decoders,
      datatype = datatype,
      fill_value = fill_value
    )
    coord <- arrayInd(i, n_chunks)
    index_in_result <- lapply(seq_len(nb_dims), function(d) {
      (coord[[d]] - 1L) * chunk_dim[[d]] + index_in_chunk[[d]]
    })
    rlang::inject(shard[!!!index_in_result] <- chunk) # nolint: implicit_assignment_linter.
  }

  return(shard)
}
